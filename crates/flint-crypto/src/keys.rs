use hkdf::Hkdf;
use sha2::Sha256;
use zeroize::Zeroizing;

pub(crate) const KEY_LEN: usize = 32;

const HKDF_SALT: &[u8] = b"flint v1";
const CONTENT_INFO: &[u8] = b"flint file content";
const INDEX_INFO: &[u8] = b"flint local index";

/// A store's random 256-bit data key. This is what the OS secret store caches for biometric unlock.
/// Zeroed on drop and never printed.
#[derive(Clone)]
pub struct Dek(Zeroizing<[u8; KEY_LEN]>);

impl Dek {
    pub(crate) fn random() -> crate::Result<Self> {
        let mut bytes = [0u8; KEY_LEN];
        getrandom::fill(&mut bytes)?;
        Ok(Self::from_bytes(bytes))
    }

    pub fn from_bytes(bytes: [u8; KEY_LEN]) -> Self {
        Self(Zeroizing::new(bytes))
    }

    /// For handing to the OS secret store. Treat as secret.
    pub fn as_bytes(&self) -> &[u8; KEY_LEN] {
        &self.0
    }
}

impl std::fmt::Debug for Dek {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Dek(..)")
    }
}

/// Everything needed to read and write one store: the DEK plus the subkeys derived from it.
#[derive(Clone)]
pub struct StoreKeys {
    key_id: u32,
    dek: Dek,
    content: Zeroizing<[u8; KEY_LEN]>,
    index: Zeroizing<[u8; KEY_LEN]>,
}

impl StoreKeys {
    /// `key_id` is the id recorded in `key.json`; it is stamped on every file so a future key
    /// rotation can tell old files from new ones.
    pub fn new(key_id: u32, dek: Dek) -> Self {
        let hkdf = Hkdf::<Sha256>::new(Some(HKDF_SALT), dek.as_bytes());
        let mut content = Zeroizing::new([0u8; KEY_LEN]);
        let mut index = Zeroizing::new([0u8; KEY_LEN]);
        hkdf.expand(CONTENT_INFO, &mut *content)
            .expect("32 bytes is a valid HKDF-SHA256 output length");
        hkdf.expand(INDEX_INFO, &mut *index)
            .expect("32 bytes is a valid HKDF-SHA256 output length");
        Self {
            key_id,
            dek,
            content,
            index,
        }
    }

    pub fn key_id(&self) -> u32 {
        self.key_id
    }

    pub fn dek(&self) -> &Dek {
        &self.dek
    }

    /// The key for the local SQLCipher index database.
    pub fn index_key(&self) -> &[u8; KEY_LEN] {
        &self.index
    }

    pub(crate) fn content_key(&self) -> &[u8; KEY_LEN] {
        &self.content
    }
}

impl std::fmt::Debug for StoreKeys {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("StoreKeys")
            .field("key_id", &self.key_id)
            .finish_non_exhaustive()
    }
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;

    pub(crate) fn test_keys() -> StoreKeys {
        StoreKeys::new(7, Dek::from_bytes([0x11; KEY_LEN]))
    }

    #[test]
    fn subkeys_match_an_independent_hkdf_implementation() {
        // Generated by a separate Python implementation (cryptography's HKDF-SHA256), not this code.
        let keys = test_keys();
        assert_eq!(
            hex::encode(keys.content_key()),
            "8047d236896b7b9779c493d8ca9cd72d9c73ab65014986e46955a23d365c6b89"
        );
        assert_eq!(
            hex::encode(keys.index_key()),
            "a6e84eaa85263909004cd4e613e1f19f05ae5bb70633ff95362356ac802499cd"
        );
    }

    #[test]
    fn content_and_index_keys_differ_from_each_other_and_from_the_dek() {
        let keys = test_keys();
        assert_ne!(keys.content_key(), keys.index_key());
        assert_ne!(keys.content_key(), keys.dek().as_bytes());
        assert_ne!(keys.index_key(), keys.dek().as_bytes());
    }

    #[test]
    fn different_deks_give_different_subkeys() {
        let other = StoreKeys::new(7, Dek::from_bytes([0x12; KEY_LEN]));
        assert_ne!(other.content_key(), test_keys().content_key());
    }

    #[test]
    fn random_deks_are_distinct() {
        assert_ne!(
            Dek::random().unwrap().as_bytes(),
            Dek::random().unwrap().as_bytes()
        );
    }

    #[test]
    fn debug_output_never_contains_key_material() {
        let keys = test_keys();
        assert_eq!(format!("{:?}", keys.dek()), "Dek(..)");
        assert_eq!(format!("{keys:?}"), "StoreKeys { key_id: 7, .. }");
    }
}
