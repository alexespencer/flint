//! The encrypted file format.
//!
//! ```text
//! offset  len  field
//!      0    4  magic "FLNT"
//!      4    1  format version (1)
//!      5    4  key id, big endian
//!      9   24  nonce (random, per write)
//!     33    n  XChaCha20-Poly1305 ciphertext, then the 16-byte tag
//! ```
//!
//! The authenticated data is bytes 0..33 (the whole header) followed by the file's store path, so a
//! header edit, a different key id, or a file moved to another name all fail to open.

use chacha20poly1305::aead::{Aead, Payload};
use chacha20poly1305::{KeyInit, XChaCha20Poly1305, XNonce};
use flint_core::StorePath;

use crate::keys::StoreKeys;
use crate::{Error, Result};

const MAGIC: [u8; 4] = *b"FLNT";
const VERSION: u8 = 1;
const NONCE_LEN: usize = 24;
const HEADER_LEN: usize = MAGIC.len() + 1 + 4 + NONCE_LEN;
const TAG_LEN: usize = 16;

/// What every sealed file adds to its plaintext.
pub const OVERHEAD: usize = HEADER_LEN + TAG_LEN;

impl StoreKeys {
    /// Encrypts `plaintext` as the contents of `path`. Output differs on every call (random nonce).
    pub fn seal(&self, path: &StorePath, plaintext: &[u8]) -> Result<Vec<u8>> {
        let mut nonce = [0u8; NONCE_LEN];
        getrandom::fill(&mut nonce)?;
        self.seal_with_nonce(path, plaintext, nonce)
    }

    fn seal_with_nonce(
        &self,
        path: &StorePath,
        plaintext: &[u8],
        nonce: [u8; NONCE_LEN],
    ) -> Result<Vec<u8>> {
        let mut out = Vec::with_capacity(HEADER_LEN + plaintext.len() + TAG_LEN);
        out.extend_from_slice(&MAGIC);
        out.push(VERSION);
        out.extend_from_slice(&self.key_id().to_be_bytes());
        out.extend_from_slice(&nonce);

        let aad = [out.as_slice(), path.as_str().as_bytes()].concat();
        let ciphertext = cipher(self)
            .encrypt(
                &XNonce::from(nonce),
                Payload {
                    msg: plaintext,
                    aad: &aad,
                },
            )
            .map_err(|_| Error::Encrypt)?;
        out.extend_from_slice(&ciphertext);
        Ok(out)
    }

    /// Decrypts a file that was sealed as the contents of `path`.
    pub fn open(&self, path: &StorePath, sealed: &[u8]) -> Result<Vec<u8>> {
        if sealed.len() < OVERHEAD || sealed[..MAGIC.len()] != MAGIC {
            return Err(Error::BadHeader);
        }
        let version = sealed[MAGIC.len()];
        if version != VERSION {
            return Err(Error::UnsupportedVersion(version));
        }
        let key_id_bytes: [u8; 4] = sealed[5..9].try_into().expect("slice is 4 bytes");
        let found = u32::from_be_bytes(key_id_bytes);
        if found != self.key_id() {
            return Err(Error::KeyIdMismatch {
                expected: self.key_id(),
                found,
            });
        }
        let nonce: [u8; NONCE_LEN] = sealed[9..HEADER_LEN].try_into().expect("slice is 24 bytes");
        let (header, ciphertext) = sealed.split_at(HEADER_LEN);

        let aad = [header, path.as_str().as_bytes()].concat();
        cipher(self)
            .decrypt(
                &XNonce::from(nonce),
                Payload {
                    msg: ciphertext,
                    aad: &aad,
                },
            )
            .map_err(|_| Error::Decrypt)
    }
}

fn cipher(keys: &StoreKeys) -> XChaCha20Poly1305 {
    XChaCha20Poly1305::new_from_slice(keys.content_key()).expect("content key is 32 bytes")
}

#[cfg(test)]
mod tests {
    use proptest::prelude::*;

    use super::*;
    use crate::keys::{Dek, tests::test_keys};

    fn path(p: &str) -> StorePath {
        StorePath::new(p).unwrap()
    }

    #[test]
    fn round_trips() {
        let keys = test_keys();
        for plaintext in [&b""[..], b"x", b"hello, flint", &vec![0xA5; 100_000]] {
            let sealed = keys.seal(&path("notes/a.md"), plaintext).unwrap();
            assert_eq!(sealed.len(), plaintext.len() + OVERHEAD);
            assert_eq!(keys.open(&path("notes/a.md"), &sealed).unwrap(), plaintext);
        }
    }

    #[test]
    fn matches_a_file_sealed_by_an_independent_implementation() {
        // Generated by a separate Python implementation of the format (HChaCha20 + ChaCha20-Poly1305
        // from the `cryptography` library, checked against the XChaCha draft's published vectors).
        // Key 0x11 x32, key id 7, nonce 0x22 x24, path "notes/a.md". If this fails, the on-disk format changed.
        let expected = hex::decode(
            "464c4e5401000000072222222222222222222222222222222222222222222222228a13c179f34d54c5467411cae752e6aeaf4621561c6f83fd90d945c5",
        )
        .unwrap();
        let keys = test_keys();
        assert_eq!(
            keys.seal_with_nonce(&path("notes/a.md"), b"hello, flint", [0x22; NONCE_LEN])
                .unwrap(),
            expected
        );
        assert_eq!(
            keys.open(&path("notes/a.md"), &expected).unwrap(),
            b"hello, flint"
        );
    }

    #[test]
    fn header_layout() {
        let sealed = test_keys()
            .seal_with_nonce(&path("a"), b"", [9; NONCE_LEN])
            .unwrap();
        assert_eq!(&sealed[..4], b"FLNT");
        assert_eq!(sealed[4], 1);
        assert_eq!(&sealed[5..9], &7u32.to_be_bytes());
        assert_eq!(&sealed[9..33], &[9; NONCE_LEN]);
        assert_eq!(sealed.len(), OVERHEAD);
    }

    #[test]
    fn same_plaintext_seals_differently_each_time() {
        let keys = test_keys();
        let a = keys.seal(&path("a.md"), b"same").unwrap();
        let b = keys.seal(&path("a.md"), b"same").unwrap();
        assert_ne!(a, b);
        assert_ne!(&a[9..33], &b[9..33], "nonces must differ");
    }

    #[test]
    fn ciphertext_does_not_contain_the_plaintext() {
        let marker = b"PLAINTEXT-MARKER-0123456789";
        let sealed = test_keys().seal(&path("a.md"), marker).unwrap();
        assert!(!sealed.windows(marker.len()).any(|w| w == marker));
    }

    #[test]
    fn a_file_moved_to_another_path_will_not_open() {
        let keys = test_keys();
        let sealed = keys.seal(&path("notes/a.md"), b"secret").unwrap();
        for other in [
            "notes/b.md",
            "other/a.md",
            "a.md",
            "notes/a.mD",
            "notes/a.md/x",
        ] {
            assert!(
                matches!(keys.open(&path(other), &sealed), Err(Error::Decrypt)),
                "{other}"
            );
        }
    }

    #[test]
    fn a_different_key_will_not_open_it() {
        let sealed = test_keys().seal(&path("a.md"), b"secret").unwrap();
        let other = StoreKeys::new(7, Dek::from_bytes([0x99; 32]));
        assert!(matches!(
            other.open(&path("a.md"), &sealed),
            Err(Error::Decrypt)
        ));
    }

    #[test]
    fn a_different_key_id_is_reported_as_such() {
        let sealed = test_keys().seal(&path("a.md"), b"secret").unwrap();
        let newer = StoreKeys::new(8, Dek::from_bytes([0x11; 32]));
        assert!(matches!(
            newer.open(&path("a.md"), &sealed),
            Err(Error::KeyIdMismatch {
                expected: 8,
                found: 7
            })
        ));
    }

    #[test]
    fn flipping_any_single_bit_anywhere_makes_it_fail() {
        let keys = test_keys();
        let sealed = keys.seal(&path("a.md"), b"some note contents").unwrap();
        for byte in 0..sealed.len() {
            for bit in 0..8 {
                let mut tampered = sealed.clone();
                tampered[byte] ^= 1 << bit;
                assert!(
                    keys.open(&path("a.md"), &tampered).is_err(),
                    "byte {byte} bit {bit} was accepted"
                );
            }
        }
    }

    #[test]
    fn every_truncation_and_extension_fails() {
        let keys = test_keys();
        let sealed = keys.seal(&path("a.md"), b"some note contents").unwrap();
        for len in 0..sealed.len() {
            assert!(
                keys.open(&path("a.md"), &sealed[..len]).is_err(),
                "length {len} was accepted"
            );
        }
        let mut longer = sealed.clone();
        longer.push(0);
        assert!(keys.open(&path("a.md"), &longer).is_err());
    }

    #[test]
    fn rejects_foreign_and_future_files() {
        let keys = test_keys();
        let sealed = keys.seal(&path("a.md"), b"x").unwrap();

        assert!(matches!(
            keys.open(&path("a.md"), b"# just a markdown file, never encrypted"),
            Err(Error::BadHeader)
        ));
        assert!(matches!(
            keys.open(&path("a.md"), &[]),
            Err(Error::BadHeader)
        ));

        let mut wrong_magic = sealed.clone();
        wrong_magic[0] = b'X';
        assert!(matches!(
            keys.open(&path("a.md"), &wrong_magic),
            Err(Error::BadHeader)
        ));

        let mut future = sealed.clone();
        future[4] = 2;
        assert!(matches!(
            keys.open(&path("a.md"), &future),
            Err(Error::UnsupportedVersion(2))
        ));
    }

    proptest! {
        #[test]
        fn round_trips_any_plaintext_and_path(plaintext in proptest::collection::vec(any::<u8>(), 0..2048), name in "[a-zA-Z0-9 _-][a-zA-Z0-9 _.-]{0,19}") {
            let keys = test_keys();
            let p = StorePath::new(format!("dir/{name}")).unwrap();
            let sealed = keys.seal(&p, &plaintext).unwrap();
            prop_assert_eq!(keys.open(&p, &sealed).unwrap(), plaintext);
        }
    }
}
